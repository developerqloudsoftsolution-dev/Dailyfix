export function normalizeReviewSlug(slug) {
  if (!slug) return 'natural-black-beard-colour';
  const s = String(slug).toLowerCase();
  if (s.includes('natural') && s.includes('black')) return 'natural-black-beard-colour';
  if (s.includes('black') && s.includes('brown')) return 'black-brown-beard-colour';
  if (s.includes('dark') && s.includes('brown')) return 'dark-brown-beard-colour';
  if (s === 'natural-black') return 'natural-black-beard-colour';
  if (s === 'black-brown') return 'black-brown-beard-colour';
  if (s === 'dark-brown') return 'dark-brown-beard-colour';
  return 'natural-black-beard-colour';
}

export function getShadeDefaultReviews(slug) {
  const norm = normalizeReviewSlug(slug);
  return SHADE_REVIEWS_MAP[norm] || SHADE_REVIEWS_MAP['natural-black-beard-colour'];
}

export function calculateReviewStats(reviews = []) {
  const list = Array.isArray(reviews) && reviews.length > 0 ? reviews : SHADE_REVIEWS_MAP['natural-black-beard-colour'];
  const total = list.length;
  const sum = list.reduce((acc, r) => acc + (Number(r.rating) || 5), 0);
  const avg = (sum / total).toFixed(1);

  const distribution = { 5: 0, 4: 0, 3: 0, 2: 0, 1: 0 };
  list.forEach((r) => {
    const star = Math.min(5, Math.max(1, Math.round(r.rating || 5)));
    distribution[star] = (distribution[star] || 0) + 1;
  });

  return {
    totalReviews: total,
    averageRating: Number(avg),
    recommendationRate: 98,
    distribution,
    satisfactionMetrics: {
      greyCoverage: 99,
      skinComfort: 98,
      naturalFinish: 97,
      longLasting: 96
    }
  };
}
